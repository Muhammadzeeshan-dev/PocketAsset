/**
 * Strict check if development OTP fallback is permissible.
 * Under NO CIRCUMSTANCES can development OTP operate in production (process.env.NODE_ENV === "production").
 * Only allowed in explicit non-production local development environments.
 */
export function isDevOtpAllowed(): boolean {
  if (process.env.NODE_ENV === "production") {
    return false;
  }
  return process.env.ALLOW_DEV_OTP === "true" || process.env.NODE_ENV === "development";
}

/**
 * Cryptographically secure 6-digit random OTP generator.
 * Never stores or returns plaintext OTP outside the generation moment.
 */
export function generateSecureOtp(): { code: string; hash: string } {
  // crypto.randomInt is cryptographically secure (inclusive min, exclusive max)
  const codeInt = crypto.randomInt(100000, 1000000);
  const code = codeInt.toString().padStart(6, "0");
  const hash = hashOtpCode(code);
  return { code, hash };
}

/**
 * Hashes a 6-digit OTP code with secret salt using SHA-256 HMAC.
 */
export function hashOtpCode(code: string): string {
  return crypto
    .createHmac("sha256", OTP_SECRET_SALT)
    .update(code.trim())
    .digest("hex");
}

/**
 * Verifies OTP code against stored hash using constant-time comparison to prevent timing attacks.
 */
export function verifyOtpCode(inputCode: string, storedHash: string): boolean {
  if (!inputCode || !storedHash) return false;
  if (!/^\d{6}$/.test(inputCode.trim())) return false;
  const inputHash = hashOtpCode(inputCode.trim());
  try {
    const inputBuffer = Buffer.from(inputHash, "hex");
    const storedBuffer = Buffer.from(storedHash, "hex");
    if (inputBuffer.length !== storedBuffer.length) return false;
    return crypto.timingSafeEqual(inputBuffer, storedBuffer);
  } catch {
    return false;
  }
}

// In-memory revocation set for admin session tokens
const revokedAdminTokens = new Set<string>();

export function revokeAdminSessionToken(tokenOrId: string): void {
  if (tokenOrId) revokedAdminTokens.add(tokenOrId);
}

export function isAdminSessionTokenRevoked(tokenOrId: string): boolean {
  return revokedAdminTokens.has(tokenOrId);
}

export function clearRevokedTokensForTesting(): void {
  revokedAdminTokens.clear();
}

/**
 * Generates signed admin verification session token.
 * Token includes admin email, expiry timestamp, unique tokenId, and HMAC signature.
 */
export function generateAdminSessionToken(
  adminEmail: string,
  durationMinutes = 30,
  tokenId = crypto.randomUUID()
): { token: string; tokenId: string; expiresAt: Date } {
  const expiresAt = new Date(Date.now() + durationMinutes * 60 * 1000);
  const payload = `${adminEmail.toLowerCase()}:${expiresAt.getTime()}:${tokenId}`;
  const signature = crypto.createHmac("sha256", ADMIN_SESSION_SECRET).update(payload).digest("hex");
  const token = Buffer.from(`${payload}:${signature}`).toString("base64url");
  return { token, tokenId, expiresAt };
}

/**
 * Verifies signed admin session token with revocation check.
 */
export function verifyAdminSessionToken(token?: string | null): {
  valid: boolean;
  adminEmail?: string;
  tokenId?: string;
  expiresAt?: Date;
  revoked?: boolean;
} {
  if (!token) return { valid: false };
  try {
    if (isAdminSessionTokenRevoked(token)) {
      return { valid: false, revoked: true };
    }

    const decoded = Buffer.from(token, "base64url").toString("utf-8");
    const parts = decoded.split(":");
    let email = "";
    let expiryStr = "";
    let tokenId = "";
    let signature = "";

    if (parts.length === 4) {
      [email, expiryStr, tokenId, signature] = parts;
    } else if (parts.length === 3) {
      [email, expiryStr, signature] = parts;
    } else {
      return { valid: false };
    }

    if (tokenId && isAdminSessionTokenRevoked(tokenId)) {
      return { valid: false, revoked: true };
    }

    const expiryTime = Number(expiryStr);
    if (!expiryTime || Date.now() > expiryTime) {
      return { valid: false };
    }

    const expectedPayload = parts.length === 4
      ? `${email}:${expiryStr}:${tokenId}`
      : `${email}:${expiryStr}`;

    const expectedSignature = crypto.createHmac("sha256", ADMIN_SESSION_SECRET).update(expectedPayload).digest("hex");
    const sigA = Buffer.from(signature, "hex");
    const sigB = Buffer.from(expectedSignature, "hex");
    if (sigA.length !== sigB.length || !crypto.timingSafeEqual(sigA, sigB)) {
      return { valid: false };
    }
    if (!isAuthorizedAdminEmail(email)) {
      return { valid: false };
    }
    return { valid: true, adminEmail: email, tokenId, expiresAt: new Date(expiryTime) };
  } catch {
    return { valid: false };
  }
}

