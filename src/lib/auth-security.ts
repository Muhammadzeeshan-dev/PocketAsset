const OTP_SECRET_SALT = process.env.OTP_SECRET_SALT || "pocketasset-secure-salt-2026";
const ADMIN_SESSION_SECRET = process.env.ADMIN_SESSION_SECRET || "pocketasset-admin-auth-secret-key-32b";

