/**
 * Device and browser detection from User-Agent string.
 * Strictly avoids claiming exact device model if not reliably detectable.
 */
export function parseUserAgent(userAgentHeader?: string | null): ParsedUserAgent {
  if (!userAgentHeader) {
    return {
      deviceType: "Desktop",
      browser: "Unknown Browser",
      os: "Unknown OS",
    };
  }

  const ua = userAgentHeader.toLowerCase();

  // 1. Device Type detection
  let deviceType: DeviceType = "Desktop";
  if (/(ipad|tablet|(android(?!.*mobile))|(windows(?!.*phone)(.*touch))|kindle|playbook|silk)/i.test(ua)) {
    deviceType = "Tablet";
  } else if (/(mobi|ipod|phone|blackberry|opera mini|fennec|minimo|symbian|psp|nintendo)/i.test(ua)) {
    deviceType = "Mobile";
  } else if (/macintosh|mac os x/i.test(ua) && !/ipad|iphone/i.test(ua)) {
    // Mac devices can be laptops or desktops; default to Laptop if portable indicators exist, else Desktop
    deviceType = /macbook/i.test(ua) ? "Laptop" : "Desktop";
  } else {
    deviceType = "Desktop";
  }

  // 2. Operating System detection
  let os = "Other OS";
  if (/windows nt 10\.0/i.test(ua)) os = "Windows 10/11";
  else if (/windows nt 6\.3/i.test(ua)) os = "Windows 8.1";
  else if (/windows nt 6\.1/i.test(ua)) os = "Windows 7";
  else if (/windows/i.test(ua)) os = "Windows";
  else if (/android/i.test(ua)) os = "Android";
  else if (/iphone|ipad|ipod/i.test(ua)) os = "iOS";
  else if (/mac os x/i.test(ua)) os = "macOS";
  else if (/cros/i.test(ua)) os = "Chrome OS";
  else if (/linux/i.test(ua)) os = "Linux";

  // 3. Browser detection
  let browser = "Web Browser";
  if (/edg\//i.test(ua)) browser = "Microsoft Edge";
  else if (/opr\/|opera\//i.test(ua)) browser = "Opera";
  else if (/chrome\//i.test(ua) && !/chromium\//i.test(ua)) browser = "Google Chrome";
  else if (/firefox\//i.test(ua)) browser = "Mozilla Firefox";
  else if (/safari\//i.test(ua) && !/chrome\//i.test(ua)) browser = "Apple Safari";
  else if (/msie|trident\//i.test(ua)) browser = "Internet Explorer";

  return { deviceType, browser, os };
}

